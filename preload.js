const { contextBridge, ipcRenderer } = require('electron');
contextBridge.exposeInMainWorld('api', {
  getConfig: () => ipcRenderer.invoke('get-config'),
  login: (id, pw) => ipcRenderer.invoke('login', id, pw),
  getSessions: () => ipcRenderer.invoke('get-sessions'),
  sessionOpen: id => ipcRenderer.invoke('session-open', id),
  sessionReveal: id => ipcRenderer.invoke('session-reveal', id),
  sessionThumb: id => ipcRenderer.invoke('session-thumb', id),
  sessionRetry: id => ipcRenderer.invoke('session-retry', id),
  getCouples: () => ipcRenderer.invoke('get-couples'),
  saveCouple: c => ipcRenderer.invoke('save-couple', c),
  deleteCouple: id => ipcRenderer.invoke('delete-couple', id),
  setActiveCouple: id => ipcRenderer.invoke('set-active-couple', id),
  openFolder: () => ipcRenderer.invoke('open-folder'),
  openCoupleFolder: id => ipcRenderer.invoke('open-couple-folder', id),
  getStartupInfo: () => ipcRenderer.invoke('get-startup-info'),
  savePhotos: payload => ipcRenderer.invoke('save-photos', payload),
  templateUkuran: () => ipcRenderer.invoke('template-ukuran'),
  countTemplates: () => ipcRenderer.invoke('count-templates'),
  listTemplates: coupleId => ipcRenderer.invoke('list-templates', coupleId),
  saveTemplate: (t, gambar) => ipcRenderer.invoke('save-template', t, gambar),
  deleteTemplate: id => ipcRenderer.invoke('delete-template', id),
  getSettings: () => ipcRenderer.invoke('get-settings'),
  saveSettings: patch => ipcRenderer.invoke('save-settings', patch),
  changeLogin: (oldPw, id, pw) => ipcRenderer.invoke('change-login', oldPw, id, pw),
  getOutDir: () => ipcRenderer.invoke('get-outdir'),
  chooseOutDir: () => ipcRenderer.invoke('choose-outdir'),
  resetOutDir: () => ipcRenderer.invoke('reset-outdir'),
  recStart: (label, opsi) => ipcRenderer.invoke('rec-start', label, opsi),
  recChunk: (id, buf) => ipcRenderer.send('rec-chunk', id, buf),
  recEnd: (id, seconds, meta) => ipcRenderer.invoke('rec-end', id, seconds, meta),
  recAbort: id => ipcRenderer.invoke('rec-abort', id),
  onRecError: cb => ipcRenderer.on('rec-error', (e, id, msg) => cb(id, msg)),
  unggahStatus: () => ipcRenderer.invoke('unggah-status'),
  unggahSimpan: cfg => ipcRenderer.invoke('unggah-simpan', cfg),
  unggahTes: () => ipcRenderer.invoke('unggah-tes'),
  unggahHasilPasang: () => ipcRenderer.invoke('unggah-hasil-pasang'),
  unggahCobaSekarang: () => ipcRenderer.invoke('unggah-coba-sekarang'),
  bukaLink: url => ipcRenderer.invoke('buka-link', url),
  salinTeks: teks => ipcRenderer.invoke('salin-teks', teks),
  catatanBaca: () => ipcRenderer.invoke('catatan-baca'),
  catatanSimpan: () => ipcRenderer.invoke('catatan-simpan'),
  catat: (pesan, tingkat) => ipcRenderer.send('catat', String(pesan), tingkat),
  onMintaTutup: cb => ipcRenderer.on('minta-tutup', () => cb()),
  cekTutup: () => ipcRenderer.invoke('cek-tutup'),
  tutupAplikasi: () => ipcRenderer.invoke('tutup-aplikasi'),
  onUnggahStatus: cb => ipcRenderer.on('unggah-status', (e, s) => cb(s)),
  sonyStatus: () => ipcRenderer.invoke('sony-status'),
  sonyLiveView: () => ipcRenderer.invoke('sony-lv'),
  sonyFoto: () => ipcRenderer.invoke('sony-foto'),
  sonyMode: jenis => ipcRenderer.invoke('sony-mode', jenis),
  sonySambungUlang: () => ipcRenderer.invoke('sony-sambung-ulang'),
  onSonyStatus: cb => ipcRenderer.on('sony-status', (e, s) => cb(s))
});
